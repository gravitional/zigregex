"""Generate src/unicode_tables.zig from Python's Unicode database.

The regex library follows Python's `re` semantics, so its character classes
and case folding are taken from the same source:

* ``\\w``: ``str.isalnum()`` or ``_``;  ``\\d``: ``str.isdecimal()``;
  ``\\s``: ``str.isspace()``;
* case-insensitive matching: two code points are equal when their simple
  lowercase mappings (``_sre.unicode_tolower``) are equal or listed together in
  ``re._casefix._EXTRA_CASES`` (e.g. ``s`` and ``ſ``).

Run with the Python whose behaviour should be matched (the differential tests
use the same one):

    ZIG=/path/to/zig uv run --no-project --python 3.14 python tools/gen_unicode_tables.py

The output is passed through `zig fmt` (``$ZIG``, default ``zig`` on PATH).
"""

import os
import subprocess
import sys
import unicodedata
from pathlib import Path

import _sre
from re._casefix import _EXTRA_CASES

OUT = Path(__file__).resolve().parent.parent / "src" / "unicode_tables.zig"
MAX = sys.maxunicode + 1


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_word(cp):
    c = chr(cp)
    return c.isalnum() or c == "_"


def fold_classes():
    parent = {}

    def find(x):
        while parent.get(x, x) != x:
            x = parent[x]
        return x

    for a, extras in _EXTRA_CASES.items():
        for b in extras:
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[max(ra, rb)] = min(ra, rb)
    groups = {}
    for cp in range(MAX):
        groups.setdefault(find(_sre.unicode_tolower(cp)), []).append(cp)
    return [g for g in groups.values() if len(g) > 1]


def emit_list(name, typ, items, per_line):
    lines = [f"pub const {name} = [_]{typ}{{"]
    for i in range(0, len(items), per_line):
        lines.append("    " + " ".join(items[i : i + per_line]))
    lines.append("};")
    return "\n".join(lines)


def main():
    def rng(rs):
        return [f".{{ 0x{a:X}, 0x{b:X} }}," for a, b in rs]

    classes = fold_classes()
    canon = sorted((cp, min(g)) for g in classes for cp in g if cp != min(g))
    orbit_members, orbit_index = [], []
    for g in sorted(classes, key=min):
        orbit_index.append((min(g), len(orbit_members), len(g)))
        orbit_members += sorted(g)

    parts = [
        "//! Generated by tools/gen_unicode_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub const unicode_version = "{unicodedata.unidata_version}";',
        "",
        "/// Inclusive code point ranges, sorted.",
        emit_list("word", "[2]u21", rng(ranges(is_word)), 6),
        "",
        emit_list("digit", "[2]u21", rng(ranges(lambda cp: chr(cp).isdecimal())), 6),
        "",
        emit_list("space", "[2]u21", rng(ranges(lambda cp: chr(cp).isspace())), 6),
        "",
        "/// (code point, canonical member of its case-fold class), sorted; only",
        "/// code points that are not their own canonical member are listed.",
        emit_list("fold_canon", "[2]u21", [f".{{ 0x{a:X}, 0x{b:X} }}," for a, b in canon], 6),
        "",
        "/// (canonical member, start, len) into `fold_members`, sorted.",
        emit_list("fold_orbits", "[3]u21", [f".{{ 0x{a:X}, {s}, {n} }}," for a, s, n in orbit_index], 6),
        "",
        emit_list("fold_members", "u21", [f"0x{cp:X}," for cp in orbit_members], 12),
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    subprocess.run([os.environ.get("ZIG", "zig"), "fmt", str(OUT)], check=True, stdout=subprocess.DEVNULL)
    print(f"wrote {OUT}: {len(canon)} folded code points, {len(orbit_index)} classes")


if __name__ == "__main__":
    main()
